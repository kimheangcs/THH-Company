const day = offset => {
  const value = new Date();
  value.setUTCHours(0, 0, 0, 0);
  value.setUTCDate(value.getUTCDate() + offset);
  return value;
};

function validatePassword(password) {
  if (typeof password !== 'string' || password.length < 12 ||
      Buffer.byteLength(password, 'utf8') > 72 || !/[A-Z]/.test(password) ||
      !/[a-z]/.test(password) || !/[0-9]/.test(password) || !/[^A-Za-z0-9]/.test(password)) {
    throw new Error('Set DEMO_PASSWORD securely: 12+ characters with upper/lowercase, number and symbol; at most 72 UTF-8 bytes.');
  }
}

async function databaseName(db) {
  const rows = await db.$queryRaw`SELECT DATABASE() AS name`;
  return rows[0]?.name;
}

async function installed(db) {
  const markers = await db.activityLog.findMany({ where: { action: 'DEMO_DATASET_CREATED', entityType: 'SYSTEM' }, select: { details: true } });
  return markers.some(row => row.details?.dataset === DATASET);
}

async function seedDemo({ db, expectedDatabase, password, onboardingEmail, storageRoot = ROOT }) {
  const actualDatabase = await databaseName(db);
  if (!expectedDatabase || actualDatabase !== expectedDatabase) {
    throw new Error('Database name does not match --expected-database. No demo data was inserted.');
  }
  if (await installed(db)) return { status: 'already-installed', ...manifest };
  validatePassword(password);
  if (onboardingEmail && (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(onboardingEmail) || /[\r\n]/.test(onboardingEmail))) {
    throw new Error('DEMO_ONBOARDING_EMAIL must be a valid email address you control.');
  }
  const emails = ACCOUNTS.map(a => a[6] === 'verify' && onboardingEmail ? onboardingEmail : emailFor(a[0]));
  const passwordHash = await bcrypt.hash(password, 12);
  const files = [];
  try {
    // Transactional ownership markers avoid overwriting records from another
    // import. Unique codes also make concurrent runs fail without partial rows.
    const result = await db.$transaction(async tx => {
      if (await installed(tx)) return { status: 'already-installed', ...manifest };
      const collisions = await Promise.all([
        tx.user.count({ where: { OR: [{ email: { in: emails } }, { employeeCode: { in: ACCOUNTS.map((_, i) => `DEMO-${String(i + 1).padStart(3, '0')}`) } }] } }),
        tx.department.count({ where: { code: { in: DEPARTMENTS.map(d => `DEMO-${d[0]}`) } } }),
        tx.project.count({ where: { code: { startsWith: 'DEMO-' } } }),
        tx.request.count({ where: { requestNo: { startsWith: 'DEMO-' } } }),
      ]);
      if (collisions.some(Boolean)) throw new Error('Demo identifiers already exist without the dataset marker. Resolve the collision; no existing data will be overwritten.');
      const departments = {};
      for (const [key, name] of DEPARTMENTS) {
        departments[key] = await tx.department.create({ data: {
          name, code: `DEMO-${key}`, description: `[${DATASET}] Sample department for endpoint demonstrations.`,
          isActive: key !== 'ARCHIVE', createdAt: day(-21),
        } });
      }
      const users = {};
      for (let i = 0; i < ACCOUNTS.length; i++) {
        const [key, firstName, lastName, role, department, status = 'ACTIVE', stage] = ACCOUNTS[i];
        users[key] = await tx.user.create({ data: {
          firstName, lastName, email: emails[i], employeeCode: `DEMO-${String(i + 1).padStart(3, '0')}`,
          role, departmentId: departments[department].id, status, passwordHash,
          jobTitle: role === 'ADMIN' ? 'Demo Administrator' : role === 'MANAGER' ? 'Demo Department Manager' : 'Demo Team Member',
          emailVerifiedAt: stage === 'verify' ? null : day(-14),
          mustChangePassword: Boolean(stage), canApproveManagerRequests: role === 'ADMIN', createdAt: day(-20),
        } });
      }
      for (const department of Object.values(departments)) {
        await tx.activityLog.create({ data: { userId: users.admin.id, action: 'DEPARTMENT_CREATED', entityType: 'DEPARTMENT', entityId: department.id, details: { dataset: DATASET, code: department.code } } });
      }
      for (const user of Object.values(users)) {
        await tx.activityLog.create({ data: { userId: users.admin.id, action: 'USER_CREATED', entityType: 'USER', entityId: user.id, details: { dataset: DATASET, role: user.role } } });
      }
      for (const [department, key] of [['IT', 'it.manager'], ['MKT', 'marketing.manager'], ['OPS', 'operations.manager']]) {
        await tx.department.update({ where: { id: departments[department].id }, data: { managerId: users[key].id } });
      }
      const projects = [];
      const projectSpecs = [
        ['PORTAL', 'Demo Employee Portal', 'IN_PROGRESS', 'IT', 'it.manager'],
        ['CAMPAIGN', 'Demo Brand Launch', 'PLANNED', 'MKT', 'marketing.manager'],
        ['HANDBOOK', 'Demo Operations Handbook', 'ON_HOLD', 'OPS', 'operations.manager'],
        ['DELIVERY', 'Demo Completed Rollout', 'COMPLETED', 'IT', 'it.manager'],
        ['RETIRED', 'Demo Retired Initiative', 'CANCELLED', 'OPS', 'operations.manager'],
      ];
      for (const [code, name, status, department, lead] of projectSpecs) {
        projects.push(await tx.project.create({ data: {
          code: `DEMO-${code}`, name, status, priority: 'MEDIUM',
          description: `[${DATASET}] Demonstrates project details, permissions, edits and status filters.`,
          createdAt: day(-14), startDate: day(-12), dueDate: day(status === 'COMPLETED' ? -1 : 21),
          completedAt: status === 'COMPLETED' ? day(-1) : null,
          ownerDepartmentId: departments[department].id, leadManagerId: users[lead].id, createdById: users.admin.id,
          departments: { create: [...new Set([department, 'IT', 'MKT'])].map(key => ({ departmentId: departments[key].id })) },
        } }));
        await tx.activityLog.create({ data: { userId: users.admin.id, action: 'PROJECT_CREATED', entityType: 'PROJECT', entityId: projects.at(-1).id, details: { dataset: DATASET, code: `DEMO-${code}` } } });
      }
      const tasks = [];
      const taskSpecs = [
        ['Design the sign-in experience', 'PENDING', 0, 'MEDIUM', 7],
        ['Connect the employee dashboard', 'IN_PROGRESS', 60, 'HIGH', 4],
        ['Review the mobile task flow', 'IN_REVIEW', 100, 'HIGH', 2],
        ['Publish the onboarding guide', 'COMPLETED', 100, 'LOW', -2],
        ['Archive the old prototype', 'CANCELLED', 20, 'LOW', 10],
        ['Fix overdue notification copy', 'IN_PROGRESS', 35, 'URGENT', -1],
        ['Prepare release screenshots', 'PENDING', 0, 'MEDIUM', 9],
        ['Check attachment downloads', 'IN_REVIEW', 100, 'MEDIUM', 3],
        ['Apply review feedback', 'IN_PROGRESS', 70, 'HIGH', 5],
        ['Update the team checklist', 'PENDING', 0, 'LOW', 8],
        ['Finalize the accessibility audit', 'COMPLETED', 100, 'MEDIUM', -1],
        ['Manager review example', 'IN_REVIEW', 100, 'HIGH', 2],
      ];
      for (let i = 0; i < taskSpecs.length; i++) {
        const [title, status, progress, priority, due] = taskSpecs[i];
        const creator = i === 11 ? users.admin : users['it.manager'];
        tasks.push(await tx.task.create({ data: {
          projectId: projects[0].id, title: `Demo: ${title}`, description: `[${DATASET}] Safe sample work item. Use the assigned employee for progress/comments/files and an independent admin or lead for reviews.`,
          status, progress, priority, departmentId: departments.IT.id, createdById: creator.id,
          createdAt: day(-7), startDate: day(-5), dueDate: day(due), completedAt: status === 'COMPLETED' ? day(-1) : null,
          assignments: { create: [{ userId: users.employee.id, assignedById: users['it.manager'].id, assignedAt: day(-6) }] },
          checklist: { create: [
            { title: 'Confirm the requirements', isCompleted: true, position: 0, createdById: users['it.manager'].id },
            { title: 'Check the Android layout', isCompleted: status === 'COMPLETED', position: 1, createdById: users['it.manager'].id },
            { title: 'Share the final update', isCompleted: status === 'COMPLETED', position: 2, createdById: users['it.manager'].id },
          ] },
          comments: { create: [{ userId: users.employee.id, createdAt: day(-3), content: 'Demo update: the first implementation is ready for feedback.' }] },
        } }));
        await tx.activityLog.create({ data: { userId: creator.id, action: 'TASK_CREATED', entityType: 'TASK', entityId: tasks[i].id, details: { dataset: DATASET, title: tasks[i].title } } });
        if (status === 'COMPLETED' || i === 8) {
          await tx.taskReview.create({ data: { taskId: tasks[i].id, reviewerId: users.admin.id, decision: status === 'COMPLETED' ? 'APPROVED' : 'CHANGES_REQUESTED', comment: status === 'COMPLETED' ? 'Demo review: approved for delivery.' : 'Demo feedback: improve the spacing and resubmit.', reviewedAt: day(-1) } });
        }
      }
      const requests = [];
      const requestSpecs = [
        ['DRAFT', 'GENERAL', 'employee', null, 'Draft workflow proposal'],
        ['PENDING', 'LEAVE', 'employee', 'it.manager', 'Annual leave request'],
        ['PENDING', 'EXPENSE', 'it.manager', 'admin', 'Conference expense approval'],
        ['IN_REVIEW', 'PURCHASE', 'employee', 'it.manager', 'Team equipment request'],
        ['APPROVED', 'IT_SUPPORT', 'employee', 'it.manager', 'Development device access'],
        ['REJECTED', 'PURCHASE', 'it.manager', 'admin', 'Additional monitor request'],
        ['CANCELLED', 'GENERAL', 'employee', 'it.manager', 'Cancelled team session'],
        ['DRAFT', 'EXPENSE', 'designer', null, 'Brand asset purchase draft'],
        ['PENDING', 'GENERAL', 'admin', 'approver', 'Independent administrator approval'],
      ];
      for (let i = 0; i < requestSpecs.length; i++) {
        const [status, type, submitterKey, approverKey, title] = requestSpecs[i];
        const submitter = users[submitterKey], approver = approverKey && users[approverKey];
        const pending = ['PENDING', 'IN_REVIEW'].includes(status), done = ['APPROVED', 'REJECTED', 'CANCELLED'].includes(status);
        const approverType = approver ? (approver.role === 'ADMIN' ? 'AUTHORIZED_ADMIN' : 'DEPARTMENT_MANAGER') : null;
        const request = await tx.request.create({ data: {
          requestNo: `DEMO-REQ-${String(i + 1).padStart(3, '0')}`, title: `Demo: ${title}`, description: `[${DATASET}] Sample ${type.toLowerCase().replaceAll('_', ' ')} request for the approval workflow.`,
          createdAt: day(-5), type, status, priority: i % 2 ? 'HIGH' : 'MEDIUM',
          amount: ['PURCHASE', 'EXPENSE'].includes(type) ? '125.50' : null, currency: 'USD',
          startDate: type === 'LEAVE' ? day(7) : null, endDate: type === 'LEAVE' ? day(9) : null,
          submittedById: submitter.id, departmentId: submitter.departmentId, approverType,
          assignedApproverId: pending ? approver.id : null, submittedAt: status === 'DRAFT' ? null : day(-3), completedAt: done ? day(-1) : null,
        } });
        requests.push(request);
        if (approver) {
          const decision = status === 'CANCELLED' ? 'SKIPPED' : done ? status : 'PENDING';
          const step = await tx.approvalStep.create({ data: { requestId: request.id, stepOrder: 1, name: 'Request approval', createdAt: day(-3), status: decision, approverType, approverId: approver.id, decidedAt: done ? day(-1) : null } });
          if (status === 'APPROVED' || status === 'REJECTED') {
            await tx.approvalAction.create({ data: { requestId: request.id, stepId: step.id, actorId: approver.id, action: status, createdAt: day(-1), comment: status === 'APPROVED' ? 'Demo: approved within the department budget.' : 'Demo: please revise the proposed budget.' } });
          }
          if (pending) await tx.notification.create({ data: { userId: approver.id, type: 'APPROVAL_REQUIRED', title: 'Demo approval required', message: `${request.title} is awaiting your decision.`, targetUrl: `/requests/${request.id}` } });
        }
        await tx.activityLog.create({ data: { userId: submitter.id, action: status === 'DRAFT' ? 'APPROVAL_REQUEST_CREATED' : 'APPROVAL_REQUEST_SUBMITTED', entityType: 'REQUEST', entityId: request.id, details: { dataset: DATASET, requestNo: request.requestNo, status } } });
      }
      // Generate the small real files required by attachment download endpoints.
      const fileContents = Buffer.from('THH Workflow demo attachment\nUse this harmless text document to demonstrate authenticated download and deletion.\n');
      for (const [kind, parentId, owner] of [['task', tasks[1].id, users.employee], ['request', requests[0].id, users.employee], ['request', requests[1].id, users.employee]]) {
        const storageName = `${crypto.randomUUID()}.txt`;
        const directory = path.join(storageRoot, kind === 'task' ? 'private_uploads/task_attachments' : 'uploads/request-attachments');
        await fs.mkdir(directory, { recursive: true });
        const destination = path.join(directory, storageName);
        await fs.writeFile(destination, fileContents, { flag: 'wx', mode: 0o600 });
        files.push(destination);
        const data = { uploadedById: owner.id, fileName: 'demo-workflow-notes.txt', mimeType: 'text/plain', fileSize: BigInt(fileContents.length), fileUrl: kind === 'task' ? storageName : `/uploads/request-attachments/${storageName}` };
        if (kind === 'task') await tx.taskAttachment.create({ data: { ...data, taskId: parentId } });
        else await tx.requestAttachment.create({ data: { ...data, requestId: parentId } });
      }
      for (const user of Object.values(users).filter(u => u.status === 'ACTIVE' && u.emailVerifiedAt && !u.mustChangePassword)) {
        await tx.notification.createMany({ data: [
          { userId: user.id, type: 'SYSTEM', title: 'Welcome to the demo workspace', message: 'Explore the role-specific menus, requests and audit history.', isRead: true, createdAt: day(-2), readAt: day(-1) },
          { userId: user.id, type: 'TASK_UPDATED', title: 'Demo project update', message: 'The employee portal has new task examples to explore.', targetUrl: `/projects/${projects[0].id}` },
        ] });
      }
      await tx.notification.create({ data: { userId: users.employee.id, type: 'TASK_ASSIGNED', title: 'Demo task assigned', message: tasks[0].title, targetUrl: `/tasks/${tasks[0].id}` } });
      await tx.activityLog.create({ data: { userId: users.admin.id, action: 'DEMO_DATASET_CREATED', entityType: 'SYSTEM', details: manifest } });
      return { status: 'created', ...manifest };
    }, { maxWait: 10000, timeout: 60000 });
    return result;
  } catch (error) {
    await Promise.all(files.map(file => fs.unlink(file).catch(() => {})));
    throw error;
  }
}

async function main() {
  require('dotenv').config({ path: path.join(ROOT, '.env'), quiet: true });
  const args = process.argv.slice(2);
  let apply = false, expectedDatabase, variable = 'DATABASE_URL';
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--apply') apply = true;
    else if (args[i] === '--dry-run') {
      if (args.includes('--apply')) throw new Error('Choose --dry-run or --apply, not both.');
    } else if (['--expected-database', '--database-variable'].includes(args[i])) {
      const value = args[++i];
      if (!value || value.startsWith('--')) throw new Error('A value is required for the database option.');
      if (args[i - 1] === '--database-variable') {
        if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(value)) throw new Error('Invalid connection variable name.');
        variable = value;
      } else expectedDatabase = value;
    } else throw new Error('Usage: node scripts/seed-demo.js [--dry-run | --apply --expected-database NAME] [--database-variable VARIABLE_NAME]');
  }
  if (!process.env[variable]) throw new Error(`Connection variable ${variable} is not set. Configure its value securely, not in chat.`);
  const target = new URL(process.env[variable]);
  if (target.protocol !== 'mysql:') throw new Error('The demo seeder requires a MySQL-compatible database.');
  const db = new PrismaClient({ datasourceUrl: process.env[variable] });
  try {
    const name = await databaseName(db);
    const alreadyInstalled = await installed(db);
    console.log(JSON.stringify({ mode: apply ? 'apply' : 'dry-run', connectionVariable: variable, host: target.hostname, database: name, alreadyInstalled, ...manifest }, null, 2));
    if (!apply) {
      console.log('Read-only preview. Use --apply --expected-database NAME after selecting the intended database.');
      return;
    }
    const result = await seedDemo({ db, expectedDatabase, password: process.env.DEMO_PASSWORD, onboardingEmail: process.env.DEMO_ONBOARDING_EMAIL });
    console.log(JSON.stringify(result, null, 2));
    console.log('Demo account emails: ' + ACCOUNTS.map(a => a[6] === 'verify' && process.env.DEMO_ONBOARDING_EMAIL ? process.env.DEMO_ONBOARDING_EMAIL : emailFor(a[0])).join(', '));
    console.log('Use the configured DEMO_PASSWORD for newly created accounts. No passwords are printed or reset.');
  } finally { await db.$disconnect(); }
}
if (require.main === module) main().catch(error => {
  // Never print a Prisma connection error that could contain a connection URL.
  if (error.constructor.name.startsWith('Prisma')) console.error('Demo seeding failed. Check database connectivity, schema migrations, privileges and unique demo identifiers. No connection credentials are printed.');
  else console.error(error.message);
  process.exitCode = 1;
});
module.exports = { seedDemo, databaseName, manifest, ACCOUNTS };
